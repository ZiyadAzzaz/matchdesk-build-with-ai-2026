"""Pin only the installed runtime dependency closure; exclude unrelated environment packages."""

from importlib.metadata import distribution
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

pending = [("starlette", frozenset()), ("uvicorn", frozenset())]
visited = set()
locked = {}
while pending:
    name, extras = pending.pop()
    name = canonicalize_name(name)
    if (name, extras) in visited:
        continue
    visited.add((name, extras))
    dist = distribution(name)
    locked[canonicalize_name(dist.metadata["Name"])] = dist.version
    for raw in dist.requires or []:
        req = Requirement(raw)
        if req.marker and not any(
            req.marker.evaluate({"extra": extra}) for extra in (extras or {""})
        ):
            continue
        if distribution(req.name).version not in req.specifier:
            raise ValueError(f"Installed dependency does not satisfy {req}")
        pending.append((req.name, frozenset(req.extras)))
target = Path(__file__).resolve().parents[1] / "requirements-lock.txt"
target.write_text(
    "# Tested Python 3.11 runtime closure. Generated by scripts/lock_runtime.py.\n"
    + "".join(f"{k}=={v}\n" for k, v in sorted(locked.items())),
    encoding="utf-8",
    newline="\n",
)
print(f"Locked {len(locked)} runtime distributions.")
